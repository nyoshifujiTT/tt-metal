"""gen_coll_routes.py - the chip-to-chip routes of the chosen form (README section 12.5, revision 8) as constexpr C++
(phase H-1 of the integrated plan, worklog 10-27).

The form is DP1 x PP4(R2) x 8chip[TP8]: 32 chips on the 8 x 4 torus, four groups of 2 x 4 chips (rows 2g, 2g+1),
group g's frames f with f mod 4 = g.  Inside a group every meeting of the design (README 12.5, step6_comm.py: AG_x,
AR_down, AR_y, AR_yf, RS_y, AG_low, AG_ids, AG_argmax and their waves) takes the form step 6 chose, and every one of
them chose a BFS-tree form (AG_tree, AG_tree+local, RS_tree): so a meeting is fully described by, for each root chip
of the group, the BFS tree of design/comm_model.py (Mesh(2, 4): dimension order vertical -> ring the short way).
  multicast (AG_tree, AG_tree+local): root r's chunk goes down r's tree; a chip forwards to its children (relay)
  reduce (RS_tree): owner o's slice goes up o's tree; a chip adds its children's partials and sends to its parent
Per chip and root the header lists: the parent, the children and the Ethernet direction of each tree edge.
Directions: N/S (rows, within the 2-row group: no wrap), E/W (the 4-column ring, both wraps).  The inter-group
hand-over (and the pass wrap 3 -> 0) pairs each chip with the counterpart chosen by free5d_v8.hand_off_pairs on the
real layout (blocks_of(8, (2, 4))), with its route on the torus (vertical first).

usage: gen_coll_routes.py <scripts dir with free5d_v8.py and design/> <step6 json> <out coll_routes.h>
"""
import json
import sys


def main():
    sdir, s6path, out = sys.argv[1], sys.argv[2], sys.argv[3]
    sys.path.insert(0, sdir + "/design")
    import comm_model as cm  # noqa: E402

    g = {"__file__": sdir + "/free5d_v8.py", "__name__": "coll_routes"}
    src = open(sdir + "/free5d_v8.py").read().replace('if __name__=="__main__": main(*sys.argv[1:])', "")
    exec(compile(src, "free5d_v8.py", "exec"), g)
    s6 = json.load(open(s6path))
    meetings = [k for k, v in s6.items() if isinstance(v, dict) and "form" in v]
    forms = {k: s6[k]["form"] for k in meetings}
    for k, f in forms.items():
        assert f in ("AG_tree", "AG_tree+local", "RS_tree"), (k, f)

    m = cm.Mesh(2, 4)
    chips = m.chips
    idx = {c: i for i, c in enumerate(chips)}

    def direction(a, b):
        if a[0] != b[0]:
            assert a[1] == b[1] and abs(a[0] - b[0]) == 1
            return "S" if b[0] > a[0] else "N"
        d = (b[1] - a[1]) % 4
        assert d in (1, 3)
        return "E" if d == 1 else "W"

    parent = [[-1] * 8 for _ in range(8)]
    pdir = [["-"] * 8 for _ in range(8)]
    kids = [[[] for _ in range(8)] for _ in range(8)]
    depth = [[0] * 8 for _ in range(8)]
    for root in chips:
        r = idx[root]
        T = m.bfs_tree(root)
        for p, ks in T.items():
            for k in ks:
                parent[r][idx[k]] = idx[p]
                pdir[r][idx[k]] = direction(k, p)
                kids[r][idx[p]].append((idx[k], direction(p, k)))
        for c in chips:
            depth[r][idx[c]] = len(m.route(root, c))
    max_kids = max(len(kids[r][c]) for r in range(8) for c in range(8))
    diam = max(depth[r][c] for r in range(8) for c in range(8))

    bl = g["blocks_of"](8, (2, 4))
    hand = []
    for gi in range(4):
        prs = g["hand_off_pairs"](bl[gi], bl[(gi + 1) % 4])
        for a, b in prs:
            route = g["TORUS"].route(a, b)
            hand.append((gi, a, b, [direction(x, y) if abs(x[0] - y[0]) in (0, 1) else ("S" if (y[0] - x[0]) % 8 == 1 else "N") for x, y in route]))
    hmax = max(len(h[3]) for h in hand)

    L = []
    w = L.append
    w("// SPDX-FileCopyrightText: © 2026 Tenstorrent USA, Inc.")
    w("//")
    w("// SPDX-License-Identifier: Apache-2.0")
    w("//")
    w("// coll_routes.h - GENERATED by tools/design/gen_coll_routes.py from design/comm_model.py, free5d_v8.py and step 6; do not")
    w("// edit.  The chip-to-chip routes of README section 12.5 (revision 8): the BFS trees of the 2 x 4 group per root chip and")
    w("// the inter-group hand-over pairs on the 8 x 4 torus.")
    w("#pragma once")
    w("#include <array>")
    w("#include <cstdint>")
    w("")
    w("namespace qwen38_coll {")
    w("")
    w("enum class Dir : uint8_t { N = 0, S = 1, E = 2, W = 3, None = 255 };")
    w("inline constexpr uint32_t kGroupChips = 8, kGroupRows = 2, kGroupCols = 4, kGroups = 4;")
    w("inline constexpr uint32_t kTreeDepthMax = %d;   // the group's diameter (hops)" % diam)
    w("inline constexpr uint32_t kMaxChildren = %d;" % max_kids)
    w("// chip index in a group = row * 4 + column (row 0 / 1 of the group, column 0..3 of the ring)")
    w("")
    w("// the meetings of the design and their forms (step 6): every one is a BFS-tree form")
    w("enum class Meeting : uint8_t { %s };" % ", ".join(k for k in meetings))
    w("inline constexpr std::array<uint32_t, %d> kMeetingBytes = {%s};   // payload per chip" % (len(meetings), ", ".join(str(int(s6[k]["bytes"])) for k in meetings)))
    w("inline constexpr std::array<bool, %d> kMeetingIsReduce = {%s};   // RS_tree (up the tree) vs AG_tree (down)" % (len(meetings), ", ".join("true" if forms[k] == "RS_tree" else "false" for k in meetings)))
    w("inline constexpr std::array<bool, %d> kMeetingLocalAdd = {%s};   // AG_tree+local: the all-reduce adds the gathered partials locally" % (len(meetings), ", ".join("true" if forms[k] == "AG_tree+local" else "false" for k in meetings)))
    # H-1 (c): the packet cut of each meeting's chunk (comm_model.chosen_cut: the fewest packets of <= 2 KiB, or that
    # count rounded up to the 2 channels, whichever the packet model finds faster); the payload of a packet is
    # 16 B aligned, the last packet takes the remainder
    cuts = []
    for k in meetings:
        P = int(s6[k]["bytes"])
        chunk = P if forms[k] != "RS_tree" else P // 8
        n = len(cm.chosen_cut(chunk))
        per = (-(-chunk // n) + 15) // 16 * 16
        cuts.append((n, per, chunk))
    w("inline constexpr std::array<uint16_t, %d> kMeetingPackets = {%s};   // packets a chunk" % (len(meetings), ", ".join(str(c[0]) for c in cuts)))
    w("inline constexpr std::array<uint32_t, %d> kMeetingPacketBytes = {%s};   // payload of a packet (16 B aligned; the last takes the rest)" % (len(meetings), ", ".join(str(c[1]) for c in cuts)))
    w("inline constexpr std::array<uint32_t, %d> kMeetingChunkBytes = {%s};   // a chunk (AG: a chip's payload; RS: 1/8 of it)" % (len(meetings), ", ".join(str(c[2]) for c in cuts)))
    w("")
    w("struct TreeNode {")
    w("    int8_t parent;                           // -1 at the root")
    w("    Dir to_parent;")
    w("    uint8_t depth;                           // hops from the root")
    w("    uint8_t n_children;")
    w("    std::array<int8_t, kMaxChildren> child;")
    w("    std::array<Dir, kMaxChildren> to_child;")
    w("};")
    w("// kTree[root][chip]")
    w("inline constexpr std::array<std::array<TreeNode, 8>, 8> kTree = {{")
    for r in range(8):
        w("    {{")
        for c in range(8):
            ks = kids[r][c] + [(-1, "None")] * (max_kids - len(kids[r][c]))
            w("        TreeNode{%d, Dir::%s, %d, %d, {%s}, {%s}}," % (
                parent[r][c], pdir[r][c] if pdir[r][c] != "-" else "None", depth[r][c], len(kids[r][c]),
                ", ".join(str(k[0]) for k in ks), ", ".join("Dir::" + k[1] for k in ks)))
        w("    }},")
    w("}};")
    w("")
    w("struct HandOver {")
    w("    uint8_t from_group;")
    w("    uint8_t from_row, from_col;              // torus coordinates (row 0..7, column 0..3)")
    w("    uint8_t to_row, to_col;")
    w("    uint8_t hops;")
    w("    std::array<Dir, %d> route;" % hmax)
    w("};")
    w("inline constexpr uint32_t kHandHopsMax = %d;" % hmax)
    w("inline constexpr std::array<HandOver, %d> kHandOver = {{" % len(hand))
    for gi, a, b, rt in hand:
        rr = rt + ["None"] * (hmax - len(rt))
        w("    HandOver{%d, %d, %d, %d, %d, %d, {%s}}," % (gi, a[0], a[1], b[0], b[1], len(rt), ", ".join("Dir::" + x for x in rr)))
    w("}};")
    w("")
    w("constexpr bool cuts_ok() {")
    w("    for (uint32_t m = 0; m < kMeetingPackets.size(); ++m) {")
    w("        if (kMeetingPackets[m] == 0 || kMeetingPacketBytes[m] % 16 || kMeetingPacketBytes[m] > 2048) return false;")
    w("        if (uint64_t(kMeetingPackets[m]) * kMeetingPacketBytes[m] < kMeetingChunkBytes[m]) return false;")
    w("        if (uint64_t(kMeetingPackets[m] - 1) * kMeetingPacketBytes[m] >= kMeetingChunkBytes[m]) return false;")
    w("    }")
    w("    return true;")
    w("}")
    w("static_assert(cuts_ok(), \"coll_routes: a meeting's packet cut does not cover its chunk within 2 KiB packets\");")
    w("// ---- static checks: every tree spans the group, parents and children agree, depths are the shortest routes ----")
    w("constexpr bool trees_ok() {")
    w("    for (uint32_t r = 0; r < 8; ++r) {")
    w("        if (kTree[r][r].parent != -1 || kTree[r][r].depth != 0) return false;")
    w("        uint32_t edges = 0;")
    w("        for (uint32_t c = 0; c < 8; ++c) {")
    w("            const auto& n = kTree[r][c];")
    w("            if (c != r) {")
    w("                if (n.parent < 0 || n.parent >= 8) return false;")
    w("                if (kTree[r][n.parent].depth + 1 != n.depth) return false;")
    w("                bool listed = false;")
    w("                for (uint32_t k = 0; k < kTree[r][n.parent].n_children; ++k) listed |= kTree[r][n.parent].child[k] == int8_t(c);")
    w("                if (!listed) return false;")
    w("            }")
    w("            const uint32_t rr = r / 4, rc = r % 4, cr = c / 4, cc = c % 4;")
    w("            const uint32_t dc = (cc + 4 - rc) % 4;")
    w("            const uint32_t ring = dc < 4 - dc ? dc : 4 - dc;")
    w("            if (n.depth != (rr != cr ? 1u : 0u) + ring) return false;")
    w("            if (n.depth > kTreeDepthMax) return false;")
    w("            edges += n.n_children;")
    w("        }")
    w("        if (edges != 7) return false;")
    w("    }")
    w("    return true;")
    w("}")
    w("static_assert(trees_ok(), \"coll_routes: a BFS tree is inconsistent\");")
    w("constexpr bool hand_ok() {")
    w("    for (const auto& h : kHandOver) {")
    w("        uint32_t r = h.from_row, c = h.from_col;")
    w("        for (uint32_t k = 0; k < h.hops; ++k) {")
    w("            switch (h.route[k]) {")
    w("                case Dir::N: r = (r + 7) % 8; break;")
    w("                case Dir::S: r = (r + 1) % 8; break;")
    w("                case Dir::E: c = (c + 1) % 4; break;")
    w("                case Dir::W: c = (c + 3) % 4; break;")
    w("                default: return false;")
    w("            }")
    w("        }")
    w("        if (r != h.to_row || c != h.to_col) return false;")
    w("        if (h.from_row / 2 != h.from_group || h.to_row / 2 != (h.from_group + 1) % kGroups) return false;")
    w("    }")
    w("    return true;")
    w("}")
    w("static_assert(hand_ok(), \"coll_routes: a hand-over route does not reach its pair\");")
    w("")
    w("}  // namespace qwen38_coll")
    open(out, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
