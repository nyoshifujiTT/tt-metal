"""gen_design_plan.py - the detailed design's unit and frame tables (README section 12.1-12.3, revision 8) as constexpr C++:
every unit of one pass on one chip of the chosen form (kind, layer, the matmul shape and weight format, the chip's bytes:
weight, input, output, work, GDN state S, L1-resident state, DRAM-only reads) and the frames (unit range, group, column,
DRAM per pass, L1 left), with static_asserts that the frames tile the units, fit the frame capacity, and sum to the
column (phase H-1 of the integrated plan, worklog 10-27).  Every number comes from the step-0 / 2 / 3 jsons.

usage: gen_design_plan.py <routing dir> <out design_plan.h>
"""
import json
import sys

KIND = {"mm": "Mm", "mm_expert": "MmExpert", "elt": "Elt", "gdr": "Gdr", "lookup": "Lookup"}
FMT = {"bf8": "Bf8", "bf4": "Bf4", "bf16": "Bf16"}


def main():
    D, out = sys.argv[1], sys.argv[2]
    FORM = sys.argv[3] if len(sys.argv) > 3 else "B"
    S0 = json.load(open(f"{D}/design_step0_units.json"))
    S2 = json.load(open(f"{D}/design_step2_account.json"))
    S3 = json.load(open(f"{D}/design_step3_frames_{FORM}.json"))
    STORED = S3["stored"]
    U0, U2, FR = S0["units"], S2["units"], S3["frames"]
    assert len(U0) == len(U2)
    kinds = sorted({u["kind"] for u in U2})
    for k in kinds:
        assert k in KIND, k
    L = []
    w = L.append
    w("// SPDX-FileCopyrightText: © 2026 Tenstorrent USA, Inc.")
    w("//")
    w("// SPDX-License-Identifier: Apache-2.0")
    w("//")
    w("// design_plan.h - GENERATED by tools/gen_design_plan.py from routing/design_step{0,2,3}*.json; do not edit.  The units of one")
    w("// pass on one chip of the chosen form (README section 12: DP1 x PP4(R%d) x 8chip[TP8 | EP1 x TPx8 tiles], ctx 1, B=1, k=1, rows %d)" % (S3["R"], S2["rows"]))
    w("// and the frames (step 3).  Bytes are this chip's share (TP %d; routed experts: the busiest chip, %.2f tiles a layer)." % (S2["tp"], S2["busiest_tiles"]))
    w("#pragma once")
    w("#include <cstdint>")
    w("")
    w("namespace qwen38_plan {")
    w("")
    w("enum class Kind : uint8_t { %s };" % ", ".join(KIND[k] for k in sorted(KIND, key=lambda k: list(KIND).index(k))))
    w("enum class Fmt : uint8_t { None, Bf8, Bf4, Bf16 };")
    w("struct Unit {")
    w("    Kind kind;")
    w("    Fmt fmt;          // weight format (matmuls)")
    w("    int8_t layer;     // -1: embed / tail / mtp")
    w("    uint32_t m, n, k; // matmul shape (rows, out columns, K) of the whole model (0 for non-matmuls)")
    w("    uint64_t w;       // weight bytes on this chip as stored (packed 8-column groups, half tiles, the form's folds)")
    w("    uint32_t in, out, work;   // row bytes in / out, work bytes on this chip")
    w("    uint32_t s;       // GDN state S bytes on this chip (read and written once a pass)")
    w("    uint32_t state_l1;   // L1-resident state bytes (conv / PLE taps)")
    w("    uint32_t dram_read;  // DRAM-only reads (embedding / n-gram rows)")
    w("};")
    w("inline constexpr uint32_t kRows = %d, kTp = %d, kPp = %d, kRounds = %d, kFrames = %d, kUnits = %d;" % (S2["rows"], S2["tp"], S3["PP"], S3["R"], len(FR), len(U2)))
    w("inline constexpr uint64_t kFrameCap = %d;   // L1 bytes a frame may use on this chip" % int(S3["cap"]))
    w("inline constexpr Unit kUnit[kUnits] = {")
    for i, (u0, u2) in enumerate(zip(U0, U2)):
        layer = u2["layer"]
        li = int(layer[1:]) if layer.startswith("L") and layer[1:].isdigit() else -1
        fmt = FMT.get(u0.get("w_fmt", ""), "None")
        m, n, k = (int(u0.get("M", 0)), int(u0.get("N", 0)), int(u0.get("K", 0)))
        name = u2["unit"].split(" ")[0].replace("*/", "* /")
        w("    {Kind::%s, Fmt::%s, %d, %d, %d, %d, %dull, %d, %d, %d, %d, %d, %d},   // %d %s"
          % (KIND[u2["kind"]], fmt, li, m, n, k, round(STORED[i]), round(u2["in_"]), round(u2["out"]), round(u2["work"]), round(u2["S"]),
             round(u2["state_l1"]), round(u2["dram_read"]), i, name))
    w("};")
    w("struct Frame { uint16_t first, end; uint8_t group; uint64_t column, dram, left; };")
    w("inline constexpr Frame kFrame[kFrames] = {")
    for f in FR:
        w("    {%d, %d, %d, %dull, %dull, %dull},   // frame %d" % (f["a"], f["z"], f["group"], round(f["column"]), round(f["dram"]), round(f["left"]), f["frame"]))
    w("};")
    w("")
    w("constexpr bool frames_tile_units() {")
    w("    if (kFrame[0].first != 0 || kFrame[kFrames - 1].end != kUnits) return false;")
    w("    for (uint32_t f = 1; f < kFrames; ++f) if (kFrame[f].first != kFrame[f - 1].end) return false;")
    w("    for (uint32_t f = 0; f < kFrames; ++f) if (kFrame[f].group != f % kPp || kFrame[f].column > kFrameCap) return false;")
    w("    return true;")
    w("}")
    w("static_assert(frames_tile_units(), \"the frames tile the units in order, frame f on group f mod PP, each within the frame capacity\");")
    w("")
    w("}  // namespace qwen38_plan")
    open(out, "w").write("\n".join(L) + "\n")
    print(f"{len(U2)} units, {len(FR)} frames -> {out}")


if __name__ == "__main__":
    main()
