"""gen_chip_l1.py - one core's L1 address map of the chosen form (README section 12.2-12.3, revision 8) as constexpr C++
(phase H-1 of the integrated plan, worklog 10-27).

Per core 1,536 KiB (Tensix L1, BH):
  [0, 40 KiB)        firmware (MEM_MAP_END, 27B README section 3)
  [40, 140 KiB)      kernel binaries + config (the budget; the one value specs cannot give: K-1 checks the build fits)
  flags              64 words x 16 B (one writer per word, NoC beat aligned)
  landing            the receive areas every core has at the same address: the multicast of a pool's output (8 x the
                     largest column of 2 rows bf16 = rows x 32 x 2 B per tile) x 2 (double buffer), the Stream-K partials
                     of one column (n_in fp32 partials of rows x 32), the Ethernet-delivered meeting chunks (the largest
                     gathered payload of step 6, double buffered), the hand-over rows (the largest cut of step 6)
  stream             the per-core stream buffers of step 3 (matmul tiles 80 KiB, GDR state unit 48 KiB, KV chunk 64 KiB)
  frame              the rest: the frame's weights, rows, work and S (step 3's capacity / 130 per core, one frame at a
                     time) + the routed reserve of 2 layers (step 7)
The static_asserts re-check: the regions are disjoint, 16 B aligned and inside 1,536 KiB; 130 x the frame region >= the
largest frame column of step 3; the landing areas hold the largest payloads of step 6.

usage: gen_chip_l1.py <routing dir> <out chip_l1.h>
"""
import json
import math
import sys

KiB = 1024


def main():
    D, out = sys.argv[1], sys.argv[2]
    FORM = sys.argv[3] if len(sys.argv) > 3 else "B"
    S3 = json.load(open(f"{D}/design_step3_frames_{FORM}.json"))
    S6 = json.load(open(f"{D}/design_step6_comm.json"))
    S2 = json.load(open(f"{D}/design_step2_account.json"))
    rows = S2["rows"]
    cores = 130
    l1 = 1536 * KiB
    fw, kern = 40 * KiB, 100 * KiB
    word = 16
    flags = 64 * word
    kmax = int(S3["kmax"])
    xrecv = 2 * rows * kmax * 2      # corrections 33-34: the whole next input of the largest-K multicast pool, 2 faces
    part = rows * 32 * 4
    n_in = int(S3["fanin"])          # correction 15: the largest Stream-K fan-in of the design's pools (step 3)
    partials = n_in * part
    meet_max = int(S3["meet_max"])
    meet_land = 2 * meet_max
    hand_max = int(S3["hand_max"])
    hand_land = hand_max

    def al(x):
        return (x + 15) // 16 * 16

    regions = []
    base = fw + kern
    for name, size, why in (
        ("Flags", flags, "64 words x 16 B, one writer per word"),
        ("XReceive", xrecv, "2 x rows %d x K %d x bf16: the next unit's whole input from the hub's multicast (no credit ring)" % (rows, kmax)),
        ("Partials", partials, "%d fp32 partials of %d x 32 (the largest Stream-K tree fan-in of the design's pools)" % (n_in, rows)),
        ("MeetLanding", meet_land, "2 x the largest meeting payload of step 6 (%d B)" % meet_max),
        ("HandLanding", hand_land, "the hand-over landing bound of step 3 (%d B; step 6b checks every cut within it)" % hand_max),
    ):
        regions.append((name, base, al(size), why))
        base += al(size)
    frame_base = base
    frame_bytes = l1 - frame_base
    cap = S3["cap"]
    col_max = max(f["column"] for f in S3["frames"])

    L = []
    w = L.append
    w("// SPDX-FileCopyrightText: © 2026 Tenstorrent USA, Inc.")
    w("//")
    w("// SPDX-License-Identifier: Apache-2.0")
    w("//")
    w("// chip_l1.h - GENERATED by tools/design/gen_chip_l1.py from routing/design_step{2,3,6}*.json; do not edit.  One core's L1")
    w("// address map of README section 12.2-12.3 (revision 8); the same map on all 130 cores of every chip.")
    w("#pragma once")
    w("#include <cstdint>")
    w("")
    w("namespace qwen38_l1 {")
    w("")
    w("inline constexpr uint32_t kCoreL1Bytes = %d;" % l1)
    w("inline constexpr uint32_t kFirmwareBytes = %d;      // MEM_MAP_END (27B README section 3)" % fw)
    w("inline constexpr uint32_t kKernelBytes = %d;      // budget: binaries + config (checked by K-1, the build product)" % kern)
    w("inline constexpr uint32_t kRows = %d;" % rows)
    for name, b, s, why in regions:
        w("inline constexpr uint32_t k%sBase = %d, k%sBytes = %d;   // %s" % (name, b, name, s, why))
    w("inline constexpr uint32_t kFrameBase = %d, kFrameBytes = %d;   // the frame's placed weights, S, L1-resident state, residual, largest work, routed reserve" % (frame_base, frame_bytes))
    w("inline constexpr uint32_t kStep3Region = %d;      // step 3's per-core frame region (must equal kFrameBytes)" % int(S3["region"]))
    w("inline constexpr uint64_t kChipFrameCapacity = %d;   // step 3: 130 x (L1 - fixed - landing) - L1-resident state" % int(cap))
    w("inline constexpr uint64_t kChipStateL1 = %d;          // step 3: conv / PLE taps resident in L1 (inside the frame region)" % int(S3["state_l1"]))
    w("inline constexpr uint64_t kLargestFrameColumn = %d;   // step 3: the largest frame (bytes on this chip)" % int(round(col_max)))
    w("inline constexpr uint32_t kMeetMaxBytes = %d, kHandMaxBytes = %d, kFanin = %d;" % (meet_max, hand_max, n_in))
    w("inline constexpr uint64_t kChipLanding = %d;   // step 3: 130 x the landing regions" % int(S3["landing"]))
    w("")
    w("static_assert(kFlagsBase == kFirmwareBytes + kKernelBytes);")
    names = [r[0] for r in regions]
    for a, b in zip(names, names[1:]):
        w("static_assert(k%sBase + k%sBytes == k%sBase);" % (a, a, b))
    w("static_assert(k%sBase + k%sBytes == kFrameBase);" % (names[-1], names[-1]))
    w("static_assert(kFrameBase + kFrameBytes == kCoreL1Bytes);")
    for n in names + ["Frame"]:
        w("static_assert(k%sBase %% 16 == 0 && k%sBytes %% 16 == 0);" % (n, n))
    w("static_assert(kMeetLandingBytes >= 2 * kMeetMaxBytes && kHandLandingBytes >= kHandMaxBytes);")
    w("static_assert(uint64_t(130) * (kFlagsBytes + kXReceiveBytes + kPartialsBytes + kMeetLandingBytes + kHandLandingBytes) == kChipLanding, \"the landing regions are step 3's\");")
    w("static_assert(kFrameBytes == kStep3Region, \"the frame region is step 3's\");")
    w("static_assert(uint64_t(130) * kFrameBytes == kChipFrameCapacity + kChipStateL1, \"the chip's frame capacity is 130 frame regions\");")
    w("static_assert(uint64_t(130) * kFrameBytes >= kLargestFrameColumn + kChipStateL1, \"the largest frame does not fit the frame regions\");")
    w("")
    w("}  // namespace qwen38_l1")
    open(out, "w").write("\n".join(L) + "\n")
    print("frame region per core %d B, x130 = %.1f MiB, largest column %.1f MiB, cap %.1f MiB" % (frame_bytes, 130 * frame_bytes / 2 ** 20, col_max / 2 ** 20, cap / 2 ** 20))


if __name__ == "__main__":
    main()
