"""gen_dram_plan.py - the DRAM read plan of the chosen form (README section 12.4.1, revision 8) as constexpr C++ (phase H-1
(b) of the integrated plan, worklog 10-27).  For every harvest case and frame: the per-core weight bytes of the placement
(step 3p: placement.timed's per-core stored bytes of every pool at its rotation), and design/dram_plan.plan's integer
program over them (every bank exactly 1/8 of the frame in 4 KiB granules, at most 2 flows a core, NOC1 responses, the
largest link load <= 0.5 x the bank time; objective: the total link load).  Per (harvest, frame, core) the header lists
the flows (bank, endpoint tile 0-2, NoC, bytes) in the order the core reads them; the bank's byte offsets follow the
order of the cores (raster path order) within the frame.

usage: gen_dram_plan.py <design dir> <routing dir> <form> <out dram_plan.h>
"""
import json
import sys
from concurrent.futures import ProcessPoolExecutor


def _plan(args):
    ddir, D, FORM, h, fi = args
    sys.path.insert(0, ddir)
    import dram_plan as DP  # noqa: E402
    import placement as PL  # noqa: E402
    import raster as R  # noqa: E402
    T4 = json.load(open(f"{D}/design_step4_item_time.json"))
    P3 = json.load(open(f"{D}/design_step3p_place_{FORM}.json"))
    fr = P3["frames"][fi]

    def pools_of(i):
        return T4[i].get("pools_by_form", {}).get(FORM, T4[i].get("pools", []))

    per = {}
    seen = {}
    for i, o in fr["rot"][str(h)]:
        k = seen.get(i, 0)
        seen[i] = k + 1
        mms = PL.tup(pools_of(i)[k])
        t, sch, fan, phys, up = PL.timed(mms, h, o)
        for q, b in phys:
            per[q] = per.get(q, 0) + b
    path = R.path(h)
    r = DP.plan({path[q]: b for q, b in per.items()}, nocs=(1,), U=0.5, time_limit=300)
    assert r is not None, (h, fi)
    flows = {q: r["flows"].get(path[q], []) for q in range(130)}
    return h, fi, {q: [list(x) for x in v] for q, v in flows.items()}, per, r["bank_bytes"], r["umax"], r["eff"]


def main():
    ddir, D, FORM, out = sys.argv[1:5]
    sys.path.insert(0, ddir)
    import raster as R  # noqa: E402
    P3 = json.load(open(f"{D}/design_step3p_place_{FORM}.json"))
    nf = len(P3["frames"])
    jobs = [(ddir, D, FORM, h, fi) for h in R.XS for fi in range(nf)]
    with ProcessPoolExecutor(max_workers=48) as ex:
        res = sorted(ex.map(_plan, jobs), key=lambda r: (r[0], r[1]))
    L = []
    w = L.append
    w("// SPDX-FileCopyrightText: © 2026 Tenstorrent USA, Inc.")
    w("//")
    w("// SPDX-License-Identifier: Apache-2.0")
    w("//")
    w("// dram_plan.h - GENERATED by tools/design/gen_dram_plan.py from design/dram_plan.py and step 3p; do not edit.  The DRAM read")
    w("// plan of README section 12.4.1 (revision 8), form %s: per harvest case, frame and core (raster path index) the flows" % FORM)
    w("// (bank, endpoint tile, NoC, bytes) that bring the core's placed weights; every bank delivers 1/8 of the frame.")
    w("#pragma once")
    w("#include <cstdint>")
    w("")
    w("namespace qwen38_dram {")
    w("")
    w("struct Flow { uint8_t bank, endpoint, noc; uint32_t bytes; };")
    w("struct CoreFlows { uint8_t n; Flow f[2]; uint32_t placed_bytes; };")
    w("inline constexpr uint32_t kHarvests = %d, kFrames = %d, kCores = 130, kBanks = 8, kGranule = 4096;" % (len(R.XS), nf))
    w("inline constexpr uint8_t kHarvestX[kHarvests] = {%s};" % ", ".join(str(x) for x in R.XS))
    w("// kPlan[harvest index][frame][raster path core]")
    w("inline constexpr CoreFlows kPlan[kHarvests][kFrames][kCores] = {")
    idx = {h: k for k, h in enumerate(R.XS)}
    by = {(h, fi): (fl, per, bb, um, ef) for h, fi, fl, per, bb, um, ef in res}
    for h in R.XS:
        w("  {")
        for fi in range(nf):
            fl, per, bb, um, ef = by[(h, fi)]
            cells = []
            for q in range(130):
                v = fl.get(q, fl.get(str(q), []))
                ff = [("{%d, %d, %d, %d}" % (b, e, n, by_)) for b, e, n, by_ in v] + ["{0, 0, 0, 0}"] * (2 - len(v))
                cells.append("{%d, {%s}, %d}" % (len(v), ", ".join(ff), int(round(per.get(q, per.get(str(q), 0))))))
            w("    {%s},   // frame %d: banks %s MiB, link max %.3f" % (", ".join(cells), fi, "/".join("%.2f" % (b / 2 ** 20) for b in bb), um))
        w("  },")
    w("};")
    w("")
    w("// every core's flows cover its placed bytes (rounded up to the granule); every bank's total is within one granule of 1/8")
    w("constexpr bool plan_ok() {")
    w("    for (uint32_t h = 0; h < kHarvests; ++h)")
    w("        for (uint32_t f = 0; f < kFrames; ++f) {")
    w("            uint64_t bank[kBanks] = {}, tot = 0;")
    w("            for (uint32_t c = 0; c < kCores; ++c) {")
    w("                const CoreFlows& x = kPlan[h][f][c];")
    w("                uint64_t s = 0;")
    w("                for (uint32_t k = 0; k < x.n; ++k) { s += x.f[k].bytes; bank[x.f[k].bank] += x.f[k].bytes; if (x.f[k].bank >= kBanks || x.f[k].endpoint >= 3) return false; }")
    w("                if (s < x.placed_bytes || s >= uint64_t(x.placed_bytes) + kGranule) { if (!(x.placed_bytes == 0 && s == 0)) return false; }")
    w("                tot += s;")
    w("            }")
    w("            for (uint32_t b = 0; b < kBanks; ++b) if (bank[b] * kBanks + kBanks * kGranule < tot || bank[b] * kBanks > tot + kBanks * kGranule) return false;")
    w("        }")
    w("    return true;")
    w("}")
    w("static_assert(plan_ok(), \"dram_plan: a core's flows do not cover its weights, or the banks are not even\");")
    w("")
    w("}  // namespace qwen38_dram")
    open(out, "w").write("\n".join(L) + "\n")
    print("%d plans; link max %.3f; efficiency min %.4f" % (len(res), max(r[5] for r in res), min(r[6] for r in res)))


if __name__ == "__main__":
    main()
