"""gen_stage_costs.py - the stage-level design (design/stages.py, README section 12.4 / 12.7, revision 8) as constexpr C++:
the specification constants with their sources, the budgets of the pipeline depths no document gives, and every stage's
cycle budget of the units the kernels implement.  The kernels and the device checks read these; nothing is typed here
(phase H-1 of the integrated plan, worklog 10-27).

usage: gen_stage_costs.py <design dir with stages.py> <out stage_costs.h>
"""
import sys

sys.path.insert(0, sys.argv[1])
import stages as SG  # noqa: E402


def main():
    out = sys.argv[2]
    L = []
    w = L.append
    w("// SPDX-FileCopyrightText: © 2026 Tenstorrent USA, Inc.")
    w("//")
    w("// SPDX-License-Identifier: Apache-2.0")
    w("//")
    w("// stage_costs.h - GENERATED by tools/gen_stage_costs.py from design/stages.py; do not edit.  The cycle budget of every stage of the")
    w("// units (README section 12.4 / 12.7, revision 8).  Cycles at the AI clock 1.35 GHz.  A kernel's stage that takes longer than its")
    w("// budget is an implementation error (rule R5: a device run checks pass / fail against these, it does not set them).")
    w("#pragma once")
    w("#include <cstdint>")
    w("")
    w("namespace qwen38_cost {")
    w("")
    w("// ---- specification constants (tt-isa-documentation unless noted) ----")
    w("inline constexpr uint32_t kMvmulLat = %d;      // MatrixUnit.md: MVMUL latency" % SG.MVMUL_LAT)
    w("inline constexpr uint32_t kUnpAddr = %d;       // UNPACR_Regular.md:680: address calculation" % SG.UNP_ADDR)
    w("inline constexpr uint32_t kUnpBytes = %d;    // UNPACR_Regular.md:349-360: Blackhole default throttle, B/cycle" % SG.UNP_BYTES)
    w("inline constexpr uint32_t kSfpLat = %d;        // VectorUnit.md: SFPADD / SFPMAD latency" % SG.SFP_LAT)
    w("inline constexpr uint32_t kPackRows = %d;      // Blackhole PACR.md: Dst rows a cycle" % SG.PACK_ROWS)
    w("inline constexpr uint32_t kRiscL1Load = %d;    // BabyRISCV/README.md: L1 load latency (L0 miss)" % SG.RISC_L1_LOAD)
    w("inline constexpr uint32_t kRiscNocReg = %d;    // BabyRISCV/README.md: NoC register load latency" % SG.RISC_NOC_REG)
    w("inline constexpr uint32_t kNiuOut = %d, kNiuIn = %d, kHop = %d, kFlitBytes = %d;   // NoC/README.md Performance" % (SG.NIU_OUT, SG.NIU_IN, SG.HOP, SG.FLIT))
    w("")
    w("// ---- budgets: pipeline depths no document gives (README 12.7; checked pass / fail on the device) ----")
    w("inline constexpr uint32_t kPPack = %d;   // packer: PACR issue -> last L1 write of a short pack" % SG.P_PACK)
    w("inline constexpr uint32_t kPUnp = %d;    // unpacker: busy -> first Src / Dst write" % SG.P_UNP)
    w("inline constexpr uint32_t kNRd = %d;     // NIU: write request issue -> first flit leaves" % SG.N_RD)
    w("")
    w("// ---- the core map's hop bounds the costs assume (core_map.h re-checks them) ----")
    w("inline constexpr uint32_t kUpHops = %d, kMcHops = %d;" % (SG.UP_HOPS, SG.MC_HOPS))
    w("inline constexpr uint32_t kUpOwn40 = %d, kUpOwn80 = %d;" % (SG.UP_OWN[40], SG.UP_OWN[80]))
    w("")
    w("// ---- stage budgets (cycles) ----")
    w("inline constexpr uint32_t kPoll = %d;             // a RISC sees a flag written by another agent (2 poll periods)" % SG.poll())
    w("inline constexpr uint32_t kIssue = %d;            // a preset NoC write: 3 stores + cmd_buf ready" % SG.issue())
    w("inline constexpr uint32_t kFinalize2 = %d;        // SFPU fp32 finalize of a 2-row column (2 phases x 2 K faces)" % SG.finalize_partial(2))
    w("inline constexpr uint32_t kPack2 = %d;            // PACR of a 2-row column (4 Dst rows) + kPPack" % SG.pack(4))
    w("inline constexpr uint32_t kUnpackPartial2 = %d;   // a 2-row fp32 partial into Dst + kPUnp" % SG.unpack_to_dst(256))
    w("inline constexpr uint32_t kAddPartial2 = %d;      // SFPU add of one 2-row fp32 partial" % SG.add_partials(2, 1))
    w("inline constexpr uint32_t kHubTail2 = %d;         // owner -> hub (14 hops) + hub poll / issue + 2 multicasts (17 hops) + receivers' poll" % SG.hub_tail(2))
    w("inline constexpr uint32_t kGdrUnit = %d;          // gated delta rule unit (value head, 8 columns), 2 rows" % SG.gdr_unit(2, 8))
    w("inline constexpr uint32_t kTopk10 = %d;           // router top-10 (16 owners + selector merge + softmax)" % SG.topk10())
    w("inline constexpr uint32_t kTopkLocal = %d, kTopkPost = %d;   // top-10 up to the merge / softmax + multicast" % (SG.topk_local(), SG.topk_post()))
    w("inline constexpr uint32_t kDramHops = %d;         // DRAM tile -> core, worst unicast over the 14 harvests (no broadcast to DRAM tiles)" % SG.DRAM_HOPS)
    w("inline constexpr uint32_t kDriscPage = %d;        // one DRISC page (27B core_plan.h kDriscPageCycles)" % SG.DRISC_PAGE)
    w("inline constexpr uint32_t kGddrPipe = %d;         // budget: GDDR read pipeline (<= 0.3 us)" % SG.GDDR_PIPE)
    w("inline constexpr uint32_t kRoutedIssue = %d;      // router unit end -> first routed page in the cores (beyond kTopkPost)" % SG.routed_issue())
    w("inline constexpr uint32_t kNormGated = %d;        // gated RMS norm per value head" % SG.norm_gated())
    w("inline constexpr uint32_t kSdpaCtx1 = %d;         // SDPA at ctx 1 + direct multicast to o_proj" % SG.sdpa_ctx1(2))
    w("inline constexpr uint32_t kConv1d = %d;           // conv1d (4 taps) + silu in the in_proj owners" % SG.conv1d_elt())
    w("inline constexpr uint32_t kHcReadElt = %d;        // a hyper-connection read's fused elementwise work" % SG.hc_read_elt(2))

    w("")
    w("// ---- matmul pools of the chosen form (rows 2): the whole unit's budget, cycles ----")
    pools = [
        ("kPoolHcDown", ((2, 320, 1280, "bf16"), (2, 4, 1280, "bf16")), "hc read down + inject [320+4, 4H/8] bf16"),
        ("kPoolHcUp", ((2, 1280, 320, "bf16"),), "hc read up [4H/8, 320] bf16"),
        ("kPoolGdnIn", ((2, 1280, 2560, "bf8"), (2, 768, 2560, "bf8"), (2, 32, 2560, "bf8"), (2, 32, 2560, "bf8")), "GDN in_proj qkv + z + a + b"),
        ("kPoolGdnOut", ((2, 2560, 768, "bf8"),), "GDN out_proj [H, 6 x 128]"),
        ("kPoolQsaIn", ((2, 1536, 2560, "bf8"), (2, 512, 2560, "bf8"), (2, 640, 2560, "bf8")), "QSA q+gate + k,v + indexer"),
        ("kPoolQsaOut", ((2, 2560, 768, "bf8"),), "QSA o_proj [H, 3 x 256]"),
        ("kPoolRouter", ((2, 160, 2560, "bf8"), (2, 512, 2560, "bf16")), "router [512, H] bf16 + shared gate/up [160, H]"),
        ("kPoolLmHead", ((2, 31040, 2560, "bf8"),), "lm_head [V/8, H]"),
    ]
    for name, mms, desc in pools:
        w("inline constexpr uint32_t %s = %d;   // %s" % (name, SG.pool_stage(mms), desc))
    w("")
    w("}  // namespace qwen38_cost")
    open(out, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
