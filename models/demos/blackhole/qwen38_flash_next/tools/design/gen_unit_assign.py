"""gen_unit_assign.py - the per-core work of every matmul pool of the chosen form on its physical placement (README
section 12.4.1, revision 8, corrections 30-46), as constexpr C++ (phase H-1 (a) of the integrated plan, worklog 10-27).

For each harvest case h (core_map.h's kTensixX order), each frame and each pool of the frame's units, step 3p chose the
rotation o of the raster path (design/raster.py: columns x ascending, y 2 -> 11) and design/placement.timed(mms, h, o)
gives the scheme (A per-column core counts, B linear Stream-K, C whole columns) chosen on that placement and the per
logical core work.  A logical core k runs at the physical core P_h[(k + o) % 130].  The header lists, per distinct
(pool shape, harvest, rotation): the scheme, the cycle budget (the placed time), the fan-in, and the works (logical core,
column, first K unit, units, role 0 owner / 1 sender, parent logical core); and per (harvest, unit) the units' pools and
their rotations.  The kernels never compute a split or a placement.

usage: gen_unit_assign.py <design dir> <routing dir> <form> <out unit_assign.h>
"""
import json
import sys


def main():
    sys.path.insert(0, sys.argv[1])
    import placement as PL  # noqa: E402
    import pool_plan as PP  # noqa: E402
    import raster as R  # noqa: E402

    D, FORM, out = sys.argv[2], sys.argv[3], sys.argv[4]
    T4 = json.load(open(f"{D}/design_step4_item_time.json"))
    P3 = json.load(open(f"{D}/design_step3p_place_{FORM}.json"))
    S2 = json.load(open(f"{D}/design_step2_account.json"))
    U = S2["units"]

    def pools_of(i):
        return T4[i].get("pools_by_form", {}).get(FORM, T4[i].get("pools", []))

    shapes = {}
    plans = []
    unit_rot = {}
    for fr in P3["frames"]:
        for h, lst in sorted(fr["rot"].items(), key=lambda kv: int(kv[0])):
            h = int(h)
            # the frame's pools in the order step 3p placed them: (unit, rotation) pairs aligned with the unit's pools
            seen = {}
            for i, o in lst:
                k = seen.get(i, 0)
                seen[i] = k + 1
                mms = PL.tup(pools_of(i)[k])
                key = (json.dumps(mms), h, o)
                if key not in shapes:
                    b = PP.plan(mms, 130, hopf=lambda a, c, H=R.hop_table(h), o=o: H[(a + o) % 130][(c + o) % 130],
                                uphop=lambda c, P=R.path(h), hub=PL.hub_of(h), o=o: R.du(P[(c + o) % 130], hub))
                    shapes[key] = len(plans)
                    plans.append((mms, h, o, b))
                unit_rot.setdefault((h, i), []).append(shapes[key])
    sch = {"A": "PerColumn", "B": "LinearStreamK", "C": "WholeColumns"}
    L = []
    w = L.append
    w("// SPDX-FileCopyrightText: © 2026 Tenstorrent USA, Inc.")
    w("//")
    w("// SPDX-License-Identifier: Apache-2.0")
    w("//")
    w("// unit_assign.h - GENERATED by tools/design/gen_unit_assign.py from design/placement.py, pool_plan.py and steps 3p / 4;")
    w("// do not edit.  The per-core work of every matmul pool of README section 12.4.1 (revision 8), form %s, on its placement" % FORM)
    w("// for each of the 14 harvest cases: logical core k runs at raster path core (k + rotation) %% 130.")
    w("#pragma once")
    w("#include <cstdint>")
    w("")
    w("namespace qwen38_assign {")
    w("")
    w("enum class Scheme : uint8_t { PerColumn = 0, LinearStreamK = 1, WholeColumns = 2 };")
    w("struct Work { uint8_t core; uint16_t column; uint16_t first_unit; uint16_t units; uint8_t role; int16_t parent; };")
    w("struct Pool { Scheme scheme; uint8_t harvest; uint8_t rotation; uint16_t columns; uint32_t first_work, n_work; uint32_t budget_cycles; uint8_t fanin; uint8_t up_hops; };")
    w("inline constexpr uint32_t kPools = %d;" % len(plans))
    total = sum(len(b["items"]) for _, _, _, b in plans)
    w("inline constexpr uint32_t kWorks = %d;" % total)
    w("inline constexpr Work kWork[kWorks] = {")
    first = []
    n = 0
    for pid, (mms, h, o, b) in enumerate(plans):
        first.append(n)
        for c, ci, u, nu, r, par in b["items"]:
            w("    {%d, %d, %d, %d, %d, %d}," % (c, ci, u, nu, r, par))
        n += len(b["items"])
    w("};")
    w("inline constexpr Pool kPool[kPools] = {")
    for (mms, h, o, b), f in zip(plans, first):
        w("    {Scheme::%s, %d, %d, %d, %d, %d, %d, %d, %d},   // %s" % (sch[b["scheme"]], h, o, len(b["cols"]), f, len(b["items"]), int(round(b["t"])), b["fan"], b["up"], json.dumps(mms)[:80]))
    w("};")
    keys = sorted(unit_rot)
    mp = max(len(v) for v in unit_rot.values())
    w("inline constexpr uint32_t kUnitPoolEntries = %d, kMaxPoolsPerUnit = %d;" % (len(keys), mp))
    w("struct UnitPools { uint8_t harvest; uint16_t unit; uint8_t n; int32_t pool[kMaxPoolsPerUnit]; };")
    w("inline constexpr UnitPools kUnitPools[kUnitPoolEntries] = {")
    for h, i in keys:
        v = unit_rot[(h, i)]
        w("    {%d, %d, %d, {%s}}," % (h, i, len(v), ", ".join(str(x) for x in v + [-1] * (mp - len(v)))))
    w("};")
    w("")
    w("// compile-time bounds (the full tree / coverage check is the host test's: test_qwen38_design_host.cpp)")
    w("constexpr bool bounds_ok() {")
    w("    for (uint32_t p = 0; p < kPools; ++p) {")
    w("        const Pool& q = kPool[p];")
    w("        if (q.first_work + q.n_work > kWorks || q.harvest > 16 || q.rotation >= 130) return false;")
    w("        if (p + 1 < kPools && kPool[p + 1].first_work != q.first_work + q.n_work) return false;")
    w("    }")
    w("    for (uint32_t i = 0; i < kWorks; ++i) if (kWork[i].core >= 130 || kWork[i].parent >= 130) return false;")
    w("    return true;")
    w("}")
    w("static_assert(bounds_ok(), \"unit_assign: an index is out of range\");")
    w("")
    w("}  // namespace qwen38_assign")
    open(out, "w").write("\n".join(L) + "\n")
    print("%d (pool, harvest, rotation) plans, %d works, %d (harvest, unit) entries" % (len(plans), total, len(keys)))


if __name__ == "__main__":
    main()
